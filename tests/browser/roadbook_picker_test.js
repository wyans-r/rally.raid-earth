const puppeteer = require('puppeteer-core'), fs = require('fs'), http = require('http'), path = require('path')
const ROOT = '/workspace/rallyraid'
const srv = http.createServer((q, r) => {
  let u = q.url.split('?')[0]
  let f = u.startsWith('/ui/') ? path.join(ROOT, 'mod', u) : path.join(ROOT, u)
  fs.readFile(f, (e, d) => { if (e) { r.writeHead(404); r.end() } else { r.writeHead(200, { 'Content-Type': f.endsWith('.css') ? 'text/css' : f.endsWith('.js') ? 'application/javascript' : 'text/html' }); r.end(d) } })
}).listen(8768)
;(async () => {
  const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] })
  const page = await browser.newPage(); await page.setViewport({ width: 1400, height: 1100 })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:8768/tests/roadbook_app_preview.html', { waitUntil: 'networkidle0' })
  await new Promise(r => setTimeout(r, 1200))
  await page.evaluate(() => { bngApi.engineLua = function (cmd, cb) { calls.push(cmd); if (cb) cb({ 1: { path: '/rallyraid/stages/ksa-alula-hegra-canyons.json', name: 'AlUla Hegra Canyons', ok: true, km: 48.2, waypoints: 9, roadbook: '/rallyraid/roadbooks/ksa-alula-hegra-canyons.roadbook.json' }, 2: { path: '/rallyraid/stages/x.json', name: 'My stage', ok: true, km: 12.3, waypoints: 4 } }) } })
  await page.click('#rb3 .rrb-btn[ng-click="openStages()"][title^="choose"]')
  await new Promise(r => setTimeout(r, 300))
  const items = await page.$$eval('#rb3 .rrb-pitem', e => e.map(x => x.innerText.replace(/\n/g, ' | ')))
  const before = await page.$eval('#rb3 .rrb-overlay .rrb-btn.on', b => b.disabled)
  await page.click('#rb3 .rrb-pitem')
  await new Promise(r => setTimeout(r, 200))
  const el = await page.$('#rb3'); await el.screenshot({ path: ROOT + '/roadbook_app_picker.png' })
  const after = await page.$eval('#rb3 .rrb-overlay .rrb-btn.on', b => b.disabled)
  await page.evaluate(() => { calls.length = 0 })
  await page.click('#rb3 .rrb-overlay .rrb-btn.on')
  await new Promise(r => setTimeout(r, 200))
  const shown = await page.$eval('#rb3 .rrb-overlay', o => getComputedStyle(o).display)
  console.log(JSON.stringify({ items, before, after, calls: await page.evaluate(() => calls), overlayAfterLoad: shown, errors }))
  await browser.close(); srv.close()
})().catch(e => { console.error(e); process.exit(1) })
